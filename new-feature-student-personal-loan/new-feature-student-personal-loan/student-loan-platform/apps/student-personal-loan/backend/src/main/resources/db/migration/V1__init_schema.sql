CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    display_name    VARCHAR(120) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE applicant (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL UNIQUE REFERENCES app_user(id),
    full_name        VARCHAR(120),
    phone            VARCHAR(20),
    city             VARCHAR(80),
    employment_type  VARCHAR(30),
    institution_name VARCHAR(120),
    monthly_income   NUMERIC(14, 2),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE loan_application (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number      VARCHAR(30) UNIQUE,
    applicant_id          BIGINT NOT NULL REFERENCES applicant(id),
    requested_amount      NUMERIC(14, 2) NOT NULL,
    tenure_months         INTEGER NOT NULL,
    interest_rate         NUMERIC(5, 2) NOT NULL,
    purpose               VARCHAR(30) NOT NULL,
    purpose_note          VARCHAR(500),
    status                VARCHAR(30) NOT NULL,
    decision_reason       VARCHAR(1000),
    submitted_at          TIMESTAMP WITH TIME ZONE,
    decided_at            TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    version               BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_loan_applicant ON loan_application(applicant_id);
CREATE INDEX idx_loan_status ON loan_application(status);

CREATE TABLE loan_status_history (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_application_id  BIGINT NOT NULL REFERENCES loan_application(id),
    from_status          VARCHAR(30),
    to_status            VARCHAR(30) NOT NULL,
    actor                VARCHAR(255) NOT NULL,
    reason               VARCHAR(1000),
    changed_at           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_history_loan ON loan_status_history(loan_application_id);

CREATE TABLE document_reference (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id            VARCHAR(40) NOT NULL UNIQUE,
    loan_application_id  BIGINT NOT NULL REFERENCES loan_application(id),
    document_type        VARCHAR(30) NOT NULL,
    original_filename    VARCHAR(255) NOT NULL,
    storage_key          VARCHAR(100) NOT NULL,
    content_type         VARCHAR(100) NOT NULL,
    size_bytes           BIGINT NOT NULL,
    status               VARCHAR(30) NOT NULL,
    validation_message   VARCHAR(500),
    uploaded_at          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_document_loan ON document_reference(loan_application_id);

CREATE TABLE outbox_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(40) NOT NULL UNIQUE,
    event_type      VARCHAR(100) NOT NULL,
    event_version   INTEGER NOT NULL,
    topic           VARCHAR(100) NOT NULL,
    aggregate_id    VARCHAR(40) NOT NULL,
    correlation_id  VARCHAR(64),
    payload         VARCHAR(4000) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    attempts        INTEGER NOT NULL DEFAULT 0,
    last_error      VARCHAR(500),
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_outbox_status ON outbox_event(status);

CREATE TABLE audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor           VARCHAR(255) NOT NULL,
    action          VARCHAR(60) NOT NULL,
    target_type     VARCHAR(60),
    target_id       VARCHAR(60),
    details         VARCHAR(1000),
    correlation_id  VARCHAR(64),
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_actor ON audit_event(actor);
